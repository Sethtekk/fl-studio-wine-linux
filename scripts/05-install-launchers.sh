#!/bin/bash
# ============================================================
# Step 5: commands and application-menu entries
#
#   ~/.local/bin/flstudio-wine   -> scripts/run-flstudio.sh
#   ~/.local/bin/splice-wine     -> scripts/run-splice.sh   (only if Splice is installed)
#   menu entries "FL Studio (Wine)", "Splice (Wine)", "Splice – repair (Wine)"
#
# The commands call the scripts in this repository, so "git pull" updates
# them. Works with every desktop that follows the freedesktop.org spec
# (KDE, GNOME, Xfce, Cinnamon, ...). Run again after installing FL or Splice.
# ============================================================
set -euo pipefail
source "$(dirname "$0")/lib/common.sh"
source "$(dirname "$0")/config.sh"

BIN_DIR="$HOME/.local/bin"
APPS_DIR="${XDG_DATA_HOME:-$HOME/.local/share}/applications"
ICON_DIR="${XDG_DATA_HOME:-$HOME/.local/share}/icons/hicolor/256x256/apps"
mkdir -p "$BIN_DIR" "$APPS_DIR" "$ICON_DIR"

step "Installing launchers"

# Remember the prefix so the launchers (and later script runs) find it.
mkdir -p "$(dirname "$FLW_CONFIG_FILE")"
printf 'WINEPREFIX=%q\nWINE_USER=%q\n' "$WINEPREFIX" "$WINE_USER" > "$FLW_CONFIG_FILE"
ok "settings saved: $FLW_CONFIG_FILE"

# Files we didn't create are backed up instead of overwritten.
backup_foreign() {
    if [ -e "$1" ] && ! grep -q 'fl-studio-wine-linux' "$1" 2>/dev/null; then
        mv "$1" "$1.bak-$(date +%Y%m%d-%H%M%S)"
        warn "existing $1 kept as .bak"
    fi
}

write_cmd() {  # name target
    backup_foreign "$BIN_DIR/$1"
    printf '#!/bin/bash\n# generated by fl-studio-wine-linux\nexec bash %q "$@"\n' "$2" > "$BIN_DIR/$1"
    chmod +x "$BIN_DIR/$1"
    ok "command: $BIN_DIR/$1"
}

# Largest icon of a Windows .exe/.ico as PNG (pure Python; ImageMagick only
# needed for old icons without a PNG frame). Skipped silently if it fails.
extract_icon() {  # source name
    local tmp got im
    tmp="$(mktemp -d)"
    got="$(python3 -I "$REPO_DIR/scripts/lib/exe-icon.py" "$1" "$tmp/icon" 2>/dev/null)" || got=""
    case "$got" in
        *.png) cp "$got" "$ICON_DIR/$2.png" ;;
        *.ico) im="$(command -v magick || command -v convert || true)"
               [ -n "$im" ] && "$im" "$got" -resize 256x256 "$ICON_DIR/$2.png" 2>/dev/null ;;
    esac
    rm -rf "$tmp"
}

desktop_entry() {  # file name comment exec icon wmclass [extra line]
    backup_foreign "$APPS_DIR/$1"
    cat > "$APPS_DIR/$1" <<EOF
[Desktop Entry]
Type=Application
Name=$2
Comment=$3
Exec=$4
Icon=$5
Terminal=false
Categories=AudioVideo;Audio;Music;
StartupNotify=true
StartupWMClass=$6
X-Generated-By=fl-studio-wine-linux
${7:-}
EOF
    ok "menu entry: $2"
}

# ── FL Studio ────────────────────────────────────────────────
write_cmd flstudio-wine "$REPO_DIR/scripts/run-flstudio.sh"
FL_EXE="$(find_fl_exe)"
FL_NAME="FL Studio"
if [ -n "$FL_EXE" ]; then
    extract_icon "$FL_EXE" fl-studio-wine
    FL_NAME="$(basename "$(dirname "$FL_EXE")")"
else
    info "FL Studio is not installed yet - the menu entry works once it is."
fi
desktop_entry fl-studio-wine.desktop "$FL_NAME (Wine)" "Music production with FL Studio under Wine" \
    "$BIN_DIR/flstudio-wine %f" fl-studio-wine fl64.exe "MimeType=application/x-flp;"

# ── Splice (optional) ────────────────────────────────────────
if [ -f "$USERPROFILE/AppData/Local/splice/Splice.exe" ]; then
    write_cmd splice-wine "$REPO_DIR/scripts/run-splice.sh"
    extract_icon "$USERPROFILE/AppData/Local/splice/app.ico" splice-wine
    desktop_entry splice-wine.desktop "Splice (Wine)" "Splice desktop app under Wine" \
        "$BIN_DIR/splice-wine" splice-wine splice.exe
    desktop_entry splice-repair-wine.desktop "Splice – repair (Wine)" \
        "Kills a hanging Splice and starts it again" \
        "$BIN_DIR/splice-wine --repair" splice-wine splice.exe
fi

update-desktop-database "$APPS_DIR" 2>/dev/null || true
if command -v kbuildsycoca6 >/dev/null; then kbuildsycoca6 >/dev/null 2>&1 || true; fi
case ":$PATH:" in *":$BIN_DIR:"*) ;; *) warn "$BIN_DIR is not in your PATH - the menu entries work anyway." ;; esac
